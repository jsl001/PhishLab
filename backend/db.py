from __future__ import annotations

import os
import sqlite3
from datetime import datetime
from pathlib import Path
from typing import Any

import psycopg
from psycopg import Cursor


class PostgresConnection:
    def __init__(self, connection: psycopg.Connection[Any]) -> None:
        self._connection = connection

    @property
    def is_postgres(self) -> bool:
        return True

    def execute(
        self,
        query: str,
        parameters: tuple[Any, ...] = (),
    ) -> Cursor[Any]:
        return self._connection.execute(query.replace("?", "%s"), parameters)

    def executemany(
        self,
        query: str,
        parameters: list[tuple[Any, ...]],
    ) -> Cursor[Any]:
        return self._connection.executemany(query.replace("?", "%s"), parameters)

    def __enter__(self) -> PostgresConnection:
        self._connection.__enter__()
        return self

    def __exit__(
        self,
        exception_type: type[BaseException] | None,
        exception: BaseException | None,
        traceback: object,
    ) -> bool | None:
        return self._connection.__exit__(exception_type, exception, traceback)

    def close(self) -> None:
        self._connection.close()


DatabaseConnection = sqlite3.Connection | PostgresConnection


def connect(sqlite_path: Path) -> DatabaseConnection:
    database_url = os.getenv("DATABASE_URL", "").strip()
    if database_url:
        return PostgresConnection(psycopg.connect(database_url, connect_timeout=10))
    if os.getenv("VERCEL"):
        raise RuntimeError("DATABASE_URL must be configured for Vercel deployments.")

    sqlite_path.parent.mkdir(parents=True, exist_ok=True)
    return sqlite3.connect(sqlite_path)


def is_postgres(connection: DatabaseConnection) -> bool:
    return isinstance(connection, PostgresConnection)


def identity_primary_key(connection: DatabaseConnection) -> str:
    if is_postgres(connection):
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return "INTEGER PRIMARY KEY AUTOINCREMENT"


def integer_type(connection: DatabaseConnection) -> str:
    return "BIGINT" if is_postgres(connection) else "INTEGER"


def display_timestamp(value: object) -> str:
    if isinstance(value, datetime):
        return value.isoformat(sep=" ")
    return str(value)
